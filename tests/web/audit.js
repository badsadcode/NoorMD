// Bench audit for the polish passes (docs/POLISH_PLAN.md): opens every bench against the mock host and reports
// what a new user would trip over — controls with no name or tooltip, buttons that are only a symbol with nothing
// to say what they do — and whether the bench has its own menus in focus mode (File, Edit, Help).
//
// Usage: node tests/web/audit.js [bench …] [--out report.md]
//   e.g. node tests/web/audit.js NoorMesh --out ../../docs/audit/NoorMesh.md
// It reuses ui.test.js's harness (the mock host, open(), waitFn()), so it sees exactly what the UI tests see.
'use strict';
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const args = process.argv.slice(2);
const outAt = args.indexOf('--out');
const out = outAt >= 0 ? args[outAt + 1] : null;
const only = args.filter((a, i) => !a.startsWith('--') && (outAt < 0 || i !== outAt + 1));

// [name, global, root selector, extra state for the mock host]
const BENCHES = [
  ['NoorMesh', 'NoorMesh', '#meshbench'], ['NoorForge', 'NoorForge', '#forgebench'], ['NoorMaterial', 'NoorTexture', '#texturebench'],
  ['NoorForm', 'NoorAssets', '#assetbench'], ['NoorSprite', 'NoorSprite', '#spritebench'], ['NoorPhoto', 'NoorPhoto', '#photobench'],
  ['NoorInk', 'NoorInk', '#inkbench'], ['NoorSound', 'NoorSound', '#soundbench'], ['NoorSequencer', 'NoorSequencer', '#seqbench'],
  ['NoorVideo', 'NoorVideo', '#videobench', { videos: true }], ['NoorMusic', 'NoorMusic', '#music', { musicTracks: 6 }],
  ['NoorRadio', 'NoorRadio', '#radiobench'], ['NoorGallery', 'NoorGallery', '#gallery'], ['NoorCalendar', 'NoorCalendar', '#calendar'],
  ['NoorStream', 'NoorStream', '#streamdesk'], ['NoorHub', 'NoorApps', '#appshub'], ['NoorVoice', 'NoorVoice', '#voicedesk'],
].filter(([name]) => !only.length || only.includes(name));

const section = `
    // ---- Bench audit (generated by audit.js)
    const AUDIT = ${JSON.stringify(BENCHES)};
    const report = [];
    for (const [name, global, rootSel, extra] of AUDIT) {
      const row = { name };
      try {
        const { page, errors } = await open(browser, url, { document: { markdown: '# x\\n', path: 'C:\\\\x.md', fileName: 'x.md', title: 'x' }, ...(extra || {}) }, { width: 1600, height: 1000 });
        await page.evaluate((g) => { const w = window[g]; if (!w.isOpen || !w.isOpen()) w.toggle(); }, global);
        await waitFn(page, (s) => { const r = document.querySelector(s); return r && !r.hidden && r.offsetParent !== null; }, rootSel, { timeout: 15000 });
        await page.waitForTimeout(600);
        Object.assign(row, await page.evaluate((s) => {
          const root = document.querySelector(s);
          const visible = (e) => e.offsetParent !== null && getComputedStyle(e).visibility !== 'hidden';
          const words = (t) => /[\\p{L}\\p{N}]{2,}/u.test(t || '');
          const nameOf = (e) => {
            const own = e.getAttribute('aria-label') || e.getAttribute('title') || (e.labels && [...e.labels].map((l) => l.textContent).join(' ')) || e.getAttribute('placeholder') || '';
            const lab = e.closest('label');
            return own || (lab ? lab.textContent : '') || (e.tagName === 'BUTTON' || e.getAttribute('role') === 'button' ? e.textContent : '') || (e.tagName === 'SELECT' && e.selectedOptions[0] ? '' : '');
          };
          const describe = (e) => (e.tagName.toLowerCase() + (e.id ? '#' + e.id : '') + (e.className && typeof e.className === 'string' ? '.' + e.className.trim().split(/\\s+/).slice(0, 2).join('.') : '') + (e.textContent.trim() ? ' "' + e.textContent.trim().slice(0, 18) + '"' : '')).slice(0, 80);
          const controls = [...root.querySelectorAll('button, [role=button], input:not([type=hidden]), select, textarea')].filter(visible);
          const unnamed = controls.filter((e) => !words(nameOf(e)));
          // A button that is only a symbol or an emoji, with no tooltip to say what it does.
          const symbolOnly = controls.filter((e) => (e.tagName === 'BUTTON' || e.getAttribute('role') === 'button') && !words(e.textContent) && !e.getAttribute('title'));
          return { controls: controls.length, unnamed: unnamed.length, unnamedList: unnamed.slice(0, 12).map(describe), symbolOnly: symbolOnly.length, symbolList: symbolOnly.slice(0, 12).map(describe) };
        }, rootSel));
        // Focus mode: the bench's own menus.
        await page.keyboard.press('F11');
        await page.waitForTimeout(500);
        row.menus = await page.evaluate(() => document.body.classList.contains('bench-app') ? [...document.querySelectorAll('#menubar .menu-title')].map((x) => x.textContent) : []);
        row.errors = errors.length;
        await page.close();
      } catch (err) { row.failed = String(err.message || err).slice(0, 160); }
      report.push(row);
      console.log('AUDIT ' + JSON.stringify(row));
    }
    const md = ['# Bench audit', '', 'Made by \`node tests/web/audit.js\` against the mock host. *Unnamed*: controls with no label, tooltip or text a screen reader (or a new user) could go by. *Symbol only*: buttons showing only a symbol or emoji with no tooltip. *Menus*: the bench\\'s own menu bar in focus mode (F11).', '',
      '| Bench | Controls | Unnamed | Symbol only | Menus in focus mode | Page errors |', '| --- | --- | --- | --- | --- | --- |',
      ...report.map((r) => r.failed ? \`| \${r.name} | — | — | — | could not open: \${r.failed} | — |\` : \`| \${r.name} | \${r.controls} | \${r.unnamed} | \${r.symbolOnly} | \${(r.menus || []).join(', ') || '**none**'} | \${r.errors} |\`), ''];
    for (const r of report) {
      if (r.failed || (!r.unnamed && !r.symbolOnly)) continue;
      md.push('## ' + r.name, '');
      if (r.unnamed) md.push('Unnamed (first ' + r.unnamedList.length + ' of ' + r.unnamed + '):', '', ...r.unnamedList.map((x) => '- \`' + x + '\`'), '');
      if (r.symbolOnly) md.push('Symbol only, no tooltip (first ' + r.symbolList.length + ' of ' + r.symbolOnly + '):', '', ...r.symbolList.map((x) => '- \`' + x + '\`'), '');
    }
    require('fs').writeFileSync(process.env.AUDIT_OUT, md.join('\\n'));
`;

const ui = fs.readFileSync(path.join(__dirname, 'ui.test.js'), 'utf8');
const i = ui.indexOf('// ---- 1. Lossless');
const head = ui.slice(0, ui.lastIndexOf('\n', i) + 1);
const tail = ui.slice(ui.lastIndexOf('  } finally {'));
const runner = path.join(__dirname, '.audit.run.js');
const report = out ? path.resolve(out) : path.join(__dirname, '.audit-report.md');
fs.writeFileSync(runner, head + section + tail);
try {
  const r = spawnSync(process.execPath, [runner], { stdio: ['ignore', 'pipe', 'inherit'], env: { ...process.env, AUDIT_OUT: report }, encoding: 'utf8' });
  for (const line of (r.stdout || '').split('\n')) if (line.startsWith('AUDIT ')) { const row = JSON.parse(line.slice(6)); console.log(row.failed ? `${row.name}: could not open (${row.failed})` : `${row.name}: ${row.controls} controls, ${row.unnamed} unnamed, ${row.symbolOnly} symbol-only; menus: ${(row.menus || []).join(', ') || 'none'}`); }
  console.log('\nReport: ' + report);
} finally { fs.unlinkSync(runner); }
