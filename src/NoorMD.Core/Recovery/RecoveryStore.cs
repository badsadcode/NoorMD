using System.Text.Json;
using NoorMD.Core.Documents;
using NoorMD.Core.Settings;

namespace NoorMD.Core.Recovery;

public sealed class RecoveryDraft
{
    public string Id { get; set; } = "";
    public string? Title { get; set; }
    public string? Path { get; set; }
    public string Markdown { get; set; } = "";
    public DateTime SavedUtc { get; set; }
    public string EncodingName { get; set; } = "UTF-8";
    public bool Bom { get; set; }
    public string Eol { get; set; } = "LF";
    public bool FinalNewline { get; set; } = true;

    public TextFormat ToFormat() => new(EncodingName, Bom, Eol == "CRLF" ? LineEnding.CRLF : LineEnding.LF, FinalNewline);
}

public sealed record RecoverySummary(string Id, string? Title, string? Path, DateTime SavedUtc, int Words);

/// <summary>
/// Unsaved-work drafts, one per open document tab. Each running window holds an exclusive lock file named by its
/// session id; its drafts are named "&lt;session&gt;-&lt;tab&gt;.json". Drafts whose session lock is not held belong to
/// a window that ended without saving (crash, power loss) and are offered for recovery, each separately.
/// Drafts written by NoorMD 1.x/2.0 previews ("&lt;session&gt;.json") are still recognised.
/// </summary>
public sealed class RecoveryStore : IDisposable
{
    private readonly string _dir;
    private FileStream? _lock;

    public string SessionId { get; }

    public RecoveryStore(string directory, string? sessionId = null)
    {
        _dir = directory;
        Directory.CreateDirectory(_dir);
        SessionId = sessionId ?? Guid.NewGuid().ToString("N");
        _lock = new FileStream(LockPath(SessionId), FileMode.Create, FileAccess.ReadWrite, FileShare.None, 1, FileOptions.DeleteOnClose);
    }

    private static bool IsHex(string s, int min, int max) => s.Length >= min && s.Length <= max && s.All(c => c is >= '0' and <= '9' or >= 'a' and <= 'f');

    /// <summary>Tab ids are short lowercase hex strings generated by the host.</summary>
    public static bool IsValidTabId(string? id) => id != null && IsHex(id, 8, 32);

    /// <summary>A draft id is "&lt;session&gt;" (legacy) or "&lt;session&gt;-&lt;tab&gt;".</summary>
    public static bool IsValidId(string? id)
    {
        if (id == null) return false;
        var dash = id.IndexOf('-');
        return dash < 0 ? IsHex(id, 32, 32) : dash == 32 && IsHex(id[..32], 32, 32) && IsValidTabId(id[33..]);
    }

    /// <summary>The tab a draft belongs to, or null for a legacy single-document draft.</summary>
    public static string? TabIdOf(string draftId) => IsValidId(draftId) && draftId.Length > 33 ? draftId[33..] : null;

    private static string SessionOf(string draftId) => draftId[..32];
    private string OwnId(string tabId) => IsValidTabId(tabId) ? $"{SessionId}-{tabId}" : throw new ArgumentException("Invalid tab id.");
    private string DraftPath(string id) => Path.Combine(_dir, id + ".json");
    private string LockPath(string id) => Path.Combine(_dir, id + ".lock");

    public void SaveOwn(string tabId, string markdown, string? title, string? path, TextFormat format)
    {
        var id = OwnId(tabId);
        var draft = new RecoveryDraft
        {
            Id = id, Title = title, Path = path, Markdown = markdown, SavedUtc = DateTime.UtcNow,
            EncodingName = format.EncodingName, Bom = format.Bom, Eol = format.Eol.ToString(), FinalNewline = format.FinalNewline,
        };
        AtomicFile.WriteAllText(DraftPath(id), JsonSerializer.Serialize(draft, SettingsStore.Json));
    }

    public void DeleteOwn(string tabId)
    {
        try { File.Delete(DraftPath(OwnId(tabId))); } catch (IOException) { /* retried on next save */ } catch (UnauthorizedAccessException) { }
    }

    public bool HasOwnDraft(string tabId) => File.Exists(DraftPath(OwnId(tabId)));

    public int OwnDraftCount => Directory.EnumerateFiles(_dir, SessionId + "-*.json").Count();

    /// <summary>Drafts left behind by windows that are no longer running.</summary>
    public List<RecoverySummary> ListOrphans()
    {
        var list = new List<RecoverySummary>();
        var live = new Dictionary<string, bool>();
        foreach (var file in Directory.EnumerateFiles(_dir, "*.json"))
        {
            var id = Path.GetFileNameWithoutExtension(file);
            if (!IsValidId(id)) continue;
            var session = SessionOf(id);
            if (session == SessionId) continue;
            if (!live.TryGetValue(session, out var isLive)) live[session] = isLive = IsLive(session);
            if (isLive) continue;
            var draft = TryRead(file);
            if (draft == null) continue;
            list.Add(new RecoverySummary(id, draft.Title, draft.Path, draft.SavedUtc, TextFileCodec.CountWords(draft.Markdown)));
        }
        return list.OrderByDescending(d => d.SavedUtc).ToList();
    }

    public RecoveryDraft? LoadOrphan(string id)
    {
        if (!IsValidId(id) || SessionOf(id) == SessionId || IsLive(SessionOf(id))) return null;
        return TryRead(DraftPath(id));
    }

    public bool DiscardOrphan(string id)
    {
        if (!IsValidId(id) || SessionOf(id) == SessionId || IsLive(SessionOf(id))) return false;
        try { File.Delete(DraftPath(id)); return true; } catch { return false; }
    }

    public int DiscardAllOrphans() => ListOrphans().Count(d => DiscardOrphan(d.Id));

    private bool IsLive(string session)
    {
        var lockPath = LockPath(session);
        if (!File.Exists(lockPath)) return false;
        try
        {
            // If we can open it exclusively, its owner is gone.
            using var probe = new FileStream(lockPath, FileMode.Open, FileAccess.ReadWrite, FileShare.None, 1, FileOptions.DeleteOnClose);
            return false;
        }
        catch (IOException) { return true; }
        catch (UnauthorizedAccessException) { return true; }
    }

    private static RecoveryDraft? TryRead(string file)
    {
        try { return JsonSerializer.Deserialize<RecoveryDraft>(File.ReadAllText(file), SettingsStore.Json); }
        catch { return null; }
    }

    public void Dispose()
    {
        _lock?.Dispose();
        _lock = null;
    }
}
